-- Push price alerts: "tell me when BTC retests $62,490". A background poller
-- (src/core/alert-poller.ts) checks active rows against live price on an
-- interval and pushes a DM the moment the level crosses. Idempotent.
create table if not exists public.price_alerts (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  platform     text not null,
  guild_id     text not null,   -- chat the alert was set from (memory scoping only)
  user_id      text not null,   -- who gets pushed the DM
  symbol       text not null,   -- Hyperliquid ticker, e.g. "BTC"
  direction    text not null check (direction in ('above', 'below')),
  target_price numeric not null,
  note         text,
  last_price   numeric,         -- previous poll's price, for edge-triggering the cross
  active       boolean not null default true,
  triggered_at timestamptz
);
create index if not exists price_alerts_active_idx on public.price_alerts (active);

alter table public.price_alerts enable row level security;
