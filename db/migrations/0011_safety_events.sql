-- Durable channel for security-backstop firings (src/core/safety.ts). Until now
-- a caught prompt-leak or a signal-language slip only hit console.warn, which is
-- ephemeral on Railway, so a real injection attempt left no trace once the log
-- rotated. This makes those events queryable from Supabase alongside usage_log.
-- Same privacy contract as usage_log: keyed by guild_id + user_id, read back
-- only as aggregates/recent-events for ops, never surfaced across users.
-- Idempotent — safe to re-run.
create table if not exists public.safety_event (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  platform      text,
  guild_id      text,
  user_id       text,
  kind          text not null,   -- 'prompt_leak' | 'signal_language'
  detail        text,            -- matched snippets, or a short note; null for prompt_leak
  question_hash text
);
create index if not exists safety_event_created_idx on public.safety_event (created_at desc);
create index if not exists safety_event_kind_created_idx on public.safety_event (kind, created_at desc);

-- Server-only app: RLS on, no policies. Service role bypasses; anon REST gets nothing.
alter table public.safety_event enable row level security;
