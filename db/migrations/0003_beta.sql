-- Private-beta guardrails: allowlist, per-request usage/cost logging, and a
-- free exact-match answer cache. Idempotent — safe to re-run.
--
-- Privacy contract: usage_log and exact_cache are keyed by guild_id + user_id
-- but are NEVER surfaced across users. Only aggregate counts (spend, message
-- totals) are read back, and the exact_cache serves an answer only to the
-- byte-identical normalized question within the same guild. No trader's raw
-- question or answer is ever shown to another trader.

-- ---- Allowlist: who may spend a cent of API budget --------------------------
create table if not exists public.beta_testers (
  platform     text not null,               -- 'discord' | 'telegram'
  platform_id  text not null,               -- discord user id / telegram user id
  name         text,
  invited_at   timestamptz not null default now(),
  primary key (platform, platform_id)
);

-- ---- Per-request usage + cost (the source of truth for spend) ---------------
create table if not exists public.usage_log (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default now(),
  platform           text,
  guild_id           text,
  user_id            text,
  question_hash      text,
  input_tokens       integer not null default 0,
  cache_write_tokens integer not null default 0,
  cache_read_tokens  integer not null default 0,
  output_tokens      integer not null default 0,
  web_searches       integer not null default 0,
  had_vision         boolean not null default false,
  tools_used         text[]  not null default '{}',
  cost_usd           numeric(10,5) not null default 0,
  latency_ms         integer,
  degraded           boolean not null default false,
  cache_hit          boolean not null default false
);
create index if not exists usage_log_created_idx on public.usage_log (created_at desc);
create index if not exists usage_log_user_created_idx on public.usage_log (user_id, created_at desc);

-- ---- Free exact-match answer cache (no embeddings needed) -------------------
-- Byte-identical normalized questions within a guild, bucketed per UTC day, so
-- "btc price?" asked 40× costs ~1 model call. Scoped by guild_id so it never
-- crosses communities.
create table if not exists public.exact_cache (
  guild_id       text not null,
  question_hash  text not null,
  bucket_date    date not null default (now() at time zone 'utc')::date,
  answer         text not null,
  sources        jsonb not null default '[]'::jsonb,
  created_at     timestamptz not null default now(),
  primary key (guild_id, question_hash, bucket_date)
);

-- Server-only app: RLS on, no policies. Service role bypasses; anon REST gets nothing.
alter table public.beta_testers enable row level security;
alter table public.usage_log   enable row level security;
alter table public.exact_cache enable row level security;
