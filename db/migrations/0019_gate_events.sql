-- Durable record of every betaGate block/degrade (src/beta/guardrails.ts). Until
-- now these only hit console.log (blockedSilent) or nothing at all (blocked,
-- serverBlock, and the feature sub-cap soft-degrades), so cap-hits, the best
-- pre-revenue willingness-to-pay signal, were invisible and unqueryable.
-- Same privacy contract as usage_log/safety_event: keyed by guild_id + user_id,
-- read back only as aggregates for ops, never surfaced across users.
-- Idempotent — safe to re-run.
create table if not exists public.gate_event (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  platform   text,
  guild_id   text,
  user_id    text,
  -- 'beta_paused' | 'guild_allowlist' | 'channel_allowlist' | 'community_channel'
  -- | 'personal_trial_lapsed' | 'guild_trial_lapsed' | 'cooldown'
  -- | 'global_spend_cap' | 'global_msg_cap' | 'guild_spend_cap' | 'user_spend_cap'
  -- | 'daily_cap' | 'monthly_cap' | 'trial_total'
  -- | 'feature_web' | 'feature_vision' | 'feature_scan'
  gate_type  text not null,
  -- The numeric cap that was hit (a daily message count, a $ amount, a cooldown
  -- in ms, a sub-cap count), null when the gate type has no single number (e.g.
  -- an allowlist miss).
  cap_value  numeric
);
create index if not exists gate_event_created_idx on public.gate_event (created_at desc);
create index if not exists gate_event_type_created_idx on public.gate_event (gate_type, created_at desc);
create index if not exists gate_event_user_created_idx on public.gate_event (user_id, created_at desc);

-- Server-only app: RLS on, no policies. Service role bypasses; anon REST gets nothing.
alter table public.gate_event enable row level security;
