-- First-party website analytics (public launch 2026-07-21). Replaces having no
-- visibility at all on the top of the funnel: until now we could see who paid
-- and who used the bot, but not how many people reached pipinvest.xyz and left.
--
-- Privacy contract (mirrors the one in 0003_beta.sql): visitor_id is a random
-- id minted in the browser's localStorage. We never store an IP address, a
-- user-agent string, or any field that identifies a person. Country is the
-- coarse Vercel edge geo header only. Nothing here is ever shown to another
-- visitor; the admin console reads aggregates.
--
-- Idempotent.
create table if not exists public.site_events (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  visitor_id    text not null,          -- random, localStorage, not a person
  session_id    text not null,          -- rolls after 30 min idle
  event         text not null,          -- 'pageview' | 'click' | 'checkout_start' | 'checkout_submit'
  path          text,                   -- '/', '/docs', ...
  target        text,                   -- click destination or CTA name
  referrer_host text,                   -- host only, never the full URL
  utm_source    text,
  utm_medium    text,
  utm_campaign  text,
  country       text,                   -- 2-letter edge geo, coarse
  device        text,                   -- 'mobile' | 'desktop'
  meta          jsonb not null default '{}'::jsonb
);

create index if not exists site_events_created_idx  on public.site_events (created_at desc);
create index if not exists site_events_event_idx    on public.site_events (event, created_at desc);
create index if not exists site_events_visitor_idx  on public.site_events (visitor_id, created_at desc);

-- Server-only app: RLS on, no policies. Service role bypasses; anon REST gets
-- nothing. The browser never reads this table, it only POSTs to /api/track.
alter table public.site_events enable row level security;
