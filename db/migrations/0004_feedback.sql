-- Pilot success metrics: answer feedback (👍/👎) + a failed-answer flag.
-- Idempotent — safe to re-run.

-- Failed / unanswerable answers (timeout or no grounded completion) — the
-- "Failed question rate" metric. Existing rows default to false.
alter table public.usage_log add column if not exists failed boolean not null default false;

-- One vote per user per answer. rating is 'up' | 'down'. rater_id lets the
-- dashboard exclude the founder and count only tester reactions.
create table if not exists public.feedback (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  platform     text,
  guild_id     text,
  message_id   text not null,
  rater_id     text not null,
  rating       text not null,
  unique (platform, message_id, rater_id)
);
create index if not exists feedback_created_idx on public.feedback (created_at desc);

alter table public.feedback enable row level security;
